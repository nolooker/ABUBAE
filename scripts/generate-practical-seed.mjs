import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const repositoryDirectory = dirname(scriptDirectory)
const contentDirectory = join(repositoryDirectory, 'content', 'practical', 'jeongchogi')
const outputDirectory = join(repositoryDirectory, 'supabase', 'seeds')

const sqlLiteral = (value) => {
  if (value === null || value === undefined) return 'NULL'
  return `'${String(value).replaceAll("'", "''")}'`
}

const sqlTextArray = (values) => `ARRAY[${values.map(sqlLiteral).join(', ')}]::text[]`

const questionUuid = (questionId) => (
  `extensions.uuid_generate_v5(extensions.uuid_ns_url(), ${sqlLiteral(`abubae:practical:${questionId}`)})`
)

const blankUuid = (questionId, blankNumber) => (
  `extensions.uuid_generate_v5(extensions.uuid_ns_url(), ${sqlLiteral(`abubae:practical:${questionId}:blank:${blankNumber}`)})`
)

export function renderPracticalSeed(round) {
  const questions = round.questions.map((question) => {
    const id = questionUuid(question.id)
    const questionSql = [
      'INSERT INTO public.questions (id, exam_id, exam_type, year, round, subject, number, content, explanation, reviewed, published)',
      'SELECT',
      `  ${id}, id, 'practical', ${round.year}, ${round.round}, ${sqlLiteral(question.subject)}, ${question.number},`,
      `  ${sqlLiteral(question.content)}, ${sqlLiteral(question.explanation)}, FALSE, TRUE`,
      "FROM public.exams WHERE slug = 'jeongchogi'",
      'ON CONFLICT (id) DO NOTHING;',
    ].join('\n')

    const answersSql = question.answers
      .filter((answer) => answer.accepted.length > 0)
      .map((answer) => [
        'INSERT INTO public.practical_answers (id, question_id, blank_number, accepted_answers)',
        `VALUES (${blankUuid(question.id, answer.blank)}, ${id}, ${answer.blank}, ${sqlTextArray(answer.accepted)})`,
        'ON CONFLICT (question_id, blank_number) DO NOTHING;',
      ].join('\n'))

    return [questionSql, ...answersSql].join('\n\n')
  })

  return [
    `-- ${round.title ?? `Practical exam ${round.year}-${round.round}`}`,
    `-- ${round.questions.length} questions`,
    ...questions,
  ].join('\n\n')
}

export function loadRoundsMatching(pattern) {
  return readdirSync(contentDirectory)
    .filter((file) => pattern.test(file))
    .sort()
    .map((file) => JSON.parse(readFileSync(join(contentDirectory, file), 'utf8')))
}

export function loadAllRounds() {
  return loadRoundsMatching(/^\d{4}-\d+\.candidates\.json$/)
}

export function renderSeedSql(round) {
  return [
    '-- Generated by scripts/generate-practical-seed.mjs. Do not edit manually.',
    'BEGIN;',
    'DO $$\nBEGIN\n  IF NOT EXISTS (SELECT 1 FROM public.exams WHERE slug = \'jeongchogi\') THEN\n    RAISE EXCEPTION \'required exam "jeongchogi" does not exist\';\n  END IF;\nEND;\n$$;',
    renderPracticalSeed(round),
    'COMMIT;',
  ].join('\n\n') + '\n'
}

export function outputFileFor(round) {
  return join(outputDirectory, `${round.year}-${round.round}-practical.sql`)
}

export function main() {
  const rounds = loadAllRounds()
  const questionCount = rounds.reduce((total, round) => total + round.questions.length, 0)

  mkdirSync(outputDirectory, { recursive: true })
  for (const round of rounds) {
    writeFileSync(outputFileFor(round), renderSeedSql(round), 'utf8')
  }

  console.log(`generated ${rounds.length} files (one per round), ${questionCount} questions -> ${outputDirectory}`)
}

const currentFile = fileURLToPath(import.meta.url)
if (process.argv[1] && process.argv[1] === currentFile) main()

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const repositoryDirectory = dirname(scriptDirectory)
const contentDirectory = join(repositoryDirectory, 'content', 'written', 'jeongchogi')
const outputFile = join(repositoryDirectory, 'supabase', 'seeds', '2021-written.sql')

const sqlLiteral = (value) => {
  if (value === null || value === undefined) return 'NULL'
  return `'${String(value).replaceAll("'", "''")}'`
}

const questionUuid = (questionId) => (
  `extensions.uuid_generate_v5(extensions.uuid_ns_url(), ${sqlLiteral(`abubae:written:${questionId}`)})`
)

const choiceUuid = (questionId, choiceNumber) => (
  `extensions.uuid_generate_v5(extensions.uuid_ns_url(), ${sqlLiteral(`abubae:written:${questionId}:choice:${choiceNumber}`)})`
)

export function renderWrittenSeed(round) {
  const questions = round.questions.map((question) => {
    const id = questionUuid(question.id)
    const questionSql = [
      'INSERT INTO public.questions (id, exam_id, exam_type, year, round, subject, number, content, explanation, reviewed, published)',
      'SELECT',
      `  ${id}, id, 'written', ${round.year}, ${round.round}, ${sqlLiteral(question.subject)}, ${question.number},`,
      `  ${sqlLiteral(question.content)}, ${sqlLiteral(question.explanation)}, FALSE, TRUE`,
      "FROM public.exams WHERE slug = 'jeongchogi'",
      'ON CONFLICT (id) DO NOTHING;',
    ].join('\n')

    const choicesSql = question.choices.map((choice, index) => {
      const choiceNumber = index + 1
      const isCorrect = question.acceptedAnswerIndexes.includes(index) ? 'TRUE' : 'FALSE'
      return [
        'INSERT INTO public.choices (id, question_id, number, content, is_correct)',
        `VALUES (${choiceUuid(question.id, choiceNumber)}, ${id}, ${choiceNumber}, ${sqlLiteral(choice)}, ${isCorrect})`,
        'ON CONFLICT (question_id, number) DO NOTHING;',
      ].join('\n')
    })

    return [questionSql, ...choicesSql].join('\n\n')
  })

  return [
    `-- ${round.title ?? `Written exam ${round.year}-${round.round}`}`,
    `-- ${round.questions.length} questions; ${round.questions.length * 4} choices`,
    ...questions,
  ].join('\n\n')
}

export function loadRoundsMatching(pattern) {
  return readdirSync(contentDirectory)
    .filter((file) => pattern.test(file))
    .sort()
    .map((file) => JSON.parse(readFileSync(join(contentDirectory, file), 'utf8')))
}

export function load2021Rounds() {
  return loadRoundsMatching(/^2021-\d+\.candidates\.json$/)
}

export function renderSeedSql(rounds) {
  return [
    '-- Generated by scripts/generate-written-seed.mjs. Do not edit manually.',
    'BEGIN;',
    'DO $$\nBEGIN\n  IF NOT EXISTS (SELECT 1 FROM public.exams WHERE slug = \'jeongchogi\') THEN\n    RAISE EXCEPTION \'required exam "jeongchogi" does not exist\';\n  END IF;\nEND;\n$$;',
    ...rounds.map(renderWrittenSeed),
    'COMMIT;',
  ].join('\n\n') + '\n'
}

export function main() {
  const rounds = load2021Rounds()
  const questionCount = rounds.reduce((total, round) => total + round.questions.length, 0)
  const choiceCount = questionCount * 4
  const sql = renderSeedSql(rounds)

  mkdirSync(dirname(outputFile), { recursive: true })
  writeFileSync(outputFile, sql, 'utf8')
  console.log(`generated ${questionCount} questions and ${choiceCount} choices`)
}

const currentFile = fileURLToPath(import.meta.url)
if (process.argv[1] && process.argv[1] === currentFile) main()
